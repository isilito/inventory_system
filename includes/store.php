<?php
/**
 * store.php
 * File-based storage — no database.
 *
 * All data lives in one PHP file (data/inventory.php) that simply returns
 * an array. It is loaded with `require` and written back with var_export().
 *
 * Shape of the data:
 *   next_id    => [table => next free id]
 *   categories => [id => [id, name, description]]
 *   items      => [id => [id, category_id, name, brand, status, notes, created_at]]
 *   variants   => [id => [id, item_id, label, sku, quantity, unit_cost, sell_price, low_threshold]]
 *   movements  => [id => [id, variant_id, type, qty_change, qty_after, unit_cost, supplier, reason, created_at]]
 */

require_once __DIR__ . '/../config.php';

/**
 * Returns the whole data array BY REFERENCE, so callers can change it.
 * Loaded once per request; created with sample data on the first run.
 */
function &data(): array
{
    static $data = null;

    if ($data === null) {
        if (is_file(DATA_FILE)) {
            $data = require DATA_FILE;
        } else {
            $data = [
                'next_id'    => [],
                'categories' => [],
                'items'      => [],
                'variants'   => [],
                'movements'  => [],
            ];
            require_once __DIR__ . '/seed.php';
            seed_sample_data();
            save_data();
        }
    }

    return $data;
}

/**
 * Writes the data array back to disk.
 * Writes to a temp file first, then renames it, so a half-written
 * file is never read by another request.
 */
function save_data(): void
{
    $data   = &data();
    $folder = dirname(DATA_FILE);

    if (!is_dir($folder)) {
        mkdir($folder, 0777, true);
    }

    $php = "<?php\n// PartsBin inventory data — generated by the app, edit through the app.\n"
         . 'return ' . var_export($data, true) . ";\n";

    $temp = DATA_FILE . '.tmp';
    file_put_contents($temp, $php, LOCK_EX);
    rename($temp, DATA_FILE);

    // Make sure PHP's opcode cache doesn't serve the old version
    if (function_exists('opcache_invalidate')) {
        opcache_invalidate(DATA_FILE, true);
    }
}

/* ---------- Basic row helpers ---------- */

// All rows of a table, keyed by id
function rows(string $table): array
{
    return data()[$table];
}

function find_row(string $table, int $id): ?array
{
    return data()[$table][$id] ?? null;
}

// Adds a row and returns its new id
function insert_row(string $table, array $row): int
{
    $data = &data();

    $id = $data['next_id'][$table] ?? 1;
    $data['next_id'][$table] = $id + 1;
    $data[$table][$id] = ['id' => $id] + $row;

    return $id;
}

function update_row(string $table, int $id, array $fields): void
{
    $data = &data();

    if (isset($data[$table][$id])) {
        $data[$table][$id] = array_merge($data[$table][$id], $fields);
    }
}

function delete_row(string $table, int $id): void
{
    $data = &data();
    unset($data[$table][$id]);
}
